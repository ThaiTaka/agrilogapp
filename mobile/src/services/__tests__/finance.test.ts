describe('financeSummary', () => {
  it('mùa vụ rỗng: biên lợi nhuận là null, không phải 0', async () => {
    const summary = await financeSummary(db, season.id);
    expect(summary.totalCost).toBe(0);
    expect(summary.profit).toBe(0);
    // "Chưa tính được" khác "bằng không" — đọc 0% nông dân sẽ tưởng hoà vốn.
    expect(summary.marginPct).toBeNull();
  });

  it('lợi nhuận = thu − chi', async () => {
    await createExpense(db, {
      seasonId: season.id,
      category: ExpenseCategory.LABOR,
      amount: 3_000_000,
    });
    await createRevenue(db, {seasonId: season.id, amount: 10_000_000});

    const summary = await financeSummary(db, season.id);
    expect(summary.profit).toBe(7_000_000);
    expect(summary.marginPct).toBe(70);
  });

  it('I9 — chi phí vật tư vào tổng đúng một lần', async () => {
    await seedAutoExpense();
    await createExpense(db, {
      seasonId: season.id,
      category: ExpenseCategory.LABOR,
      amount: 500_000,
    });

    const summary = await financeSummary(db, season.id);
    expect(summary.totalCost).toBe(800_000);
    expect(summary.autoGeneratedCost).toBe(300_000);
    expect(summary.manualCost).toBe(500_000);
    expect(summary.expenseCount).toBe(2);
  });

  it('phân tích theo nhóm, sắp xếp giảm dần', async () => {
    for (const [category, amount] of [
      [ExpenseCategory.LABOR, 600_000],
      [ExpenseCategory.TRANSPORT, 300_000],
      [ExpenseCategory.LABOR, 100_000],
    ] as const) {
      await createExpense(db, {seasonId: season.id, category, amount});
    }

    const summary = await financeSummary(db, season.id);
    expect(summary.costByCategory[0]!.category).toBe(ExpenseCategory.LABOR);
    expect(summary.costByCategory[0]!.amount).toBe(700_000);
    expect(summary.costByCategory[0]!.sharePct).toBe(70);
    expect(summary.costByCategory[1]!.sharePct).toBe(30);
  });

  it('xoá nhật ký thì tổng chi giảm theo', async () => {
    await seedAutoExpense();
    expect((await financeSummary(db, season.id)).totalCost).toBe(300_000);

    const entries = await db.get('diary_entries').query().fetch();
    await deleteDiaryEntry(db, entries[0]!.id);

    expect((await financeSummary(db, season.id)).totalCost).toBe(0);
  });
});
