describe('resolveRevenueAmount', () => {
  it('tính từ sản lượng × đơn giá khi không có thành tiền', () => {
    expect(
      resolveRevenueAmount({seasonId: 's', quantity: 1250, unitPrice: 8500}),
    ).toBe(10_625_000);
  });

  it('thành tiền nhập tay luôn thắng phép nhân', () => {
    // Giao dịch thật hay bị làm tròn xuống, trừ hao độ ẩm, hoặc trả một phần.
    expect(
      resolveRevenueAmount({
        seasonId: 's',
        quantity: 1250,
        unitPrice: 8500,
        amount: 10_000_000,
      }),
    ).toBe(10_000_000);
  });

  it('thiếu cả hai thì báo lỗi', () => {
    expect(() => resolveRevenueAmount({seasonId: 's', quantity: 1250})).toThrow(
      ValidationError,
    );
  });

  it('từ chối số âm', () => {
    expect(() => resolveRevenueAmount({seasonId: 's', amount: -1})).toThrow(
      ValidationError,
    );
  });
});

describe('Khoản thu', () => {
  it('tạo và tính thành tiền', async () => {
    const revenue = await createRevenue(db, {
      seasonId: season.id,
      quantity: 1000,
      unit: 'kg',
      unitPrice: 8000,
    });
    expect(revenue.amount).toBe(8_000_000);
  });

  it('đổi đơn giá thì tính lại thành tiền', async () => {
    const revenue = await createRevenue(db, {
      seasonId: season.id,
      quantity: 1000,
      unit: 'kg',
      unitPrice: 8000,
    });
    await updateRevenue(db, revenue.id, {unitPrice: 9000});

    const fresh = await db.get<Revenue>('revenues').find(revenue.id);
    expect(fresh.amount).toBe(9_000_000);
  });

  it('thành tiền nhập tay không bị ghi đè', async () => {
    const revenue = await createRevenue(db, {
      seasonId: season.id,
      quantity: 1000,
      unit: 'kg',
      unitPrice: 8000,
    });
    await updateRevenue(db, revenue.id, {unitPrice: 9000, amount: 8_500_000});

    const fresh = await db.get<Revenue>('revenues').find(revenue.id);
    expect(fresh.amount).toBe(8_500_000);
  });
});

